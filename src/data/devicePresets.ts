export type DeviceForm = 'phone' | 'tablet' | 'laptop' | 'desktop' | 'freeform'

export type DeviceCategory =
  | 'favorites'
  | 'iphone'
  | 'android'
  | 'xiaomi'
  | 'ipad'
  | 'android-tablet'
  | 'laptop'
  | 'desktop'
  | 'custom'

export type DevicePreset = {
  id: string
  name: string
  width: number
  height: number
  scale?: number
  platform?: string
  ppi?: number
  form?: DeviceForm
  category: DeviceCategory
}

export type DeviceCategoryGroup = {
  id: DeviceCategory
  label: string
  presets: DevicePreset[]
}

/** Default workspace order: Mobile → Tablet → Laptop. */
