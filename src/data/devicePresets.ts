const CATEGORY_ORDER: { id: DeviceCategory; label: string }[] = [
  { id: 'favorites', label: 'Favorites' },
  { id: 'iphone', label: 'iPhone' },
  { id: 'android', label: 'Android phones' },
  { id: 'xiaomi', label: 'Xiaomi / Redmi / POCO' },
  { id: 'ipad', label: 'iPad' },
  { id: 'android-tablet', label: 'Android tablets' },
  { id: 'laptop', label: 'MacBooks & Laptops' },
  { id: 'desktop', label: 'Escritorios' },
  { id: 'custom', label: 'Custom' },
]

export function getPresetById(id: string): DevicePreset | undefined {
  return DEVICE_PRESETS.find((item) => item.id === id)
}

export function getDeviceGroups(): DeviceCategoryGroup[] {
  return CATEGORY_ORDER.map((category) => ({
    id: category.id,
    label: category.label,
    presets: DEVICE_PRESETS.filter((item) => item.category === category.id),
  })).filter((group) => group.presets.length > 0)
}

/** Presets for the "Add pane" menu (subset + full groups). */
export function getAddPaneGroups(): DeviceCategoryGroup[] {
  return getDeviceGroups().filter((group) => group.id !== 'favorites')
}

/** Label format: "320×568px" */
export function formatSizeLabel(width: number, height: number) {
  return `${Math.round(width)}×${Math.round(height)}px`
}

export function formatDeviceMeta(opts: {
  width: number
  height: number
  platform?: string
  ppi?: number
}) {
  const platform = opts.platform ?? 'Custom'
  const ppi = opts.ppi ?? 96
  return `${platform} · ${opts.width}×${opts.height}/${ppi}ppi`
}
